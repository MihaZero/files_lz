import pandas as pd # подключаем библиотеку pandas для работы с таблицами и файлами
import matplotlib.pyplot as plt # подключаем библиотеку для рисования графиков

tablica = pd.read_parquet("titanic.parquet") # читаем исходный файл
tablica.to_csv("titanic.csv", index=False) # сохраняем таблицу в формат csv (index=False убирает лишний столбец с номерами строк)
print("Файл успешно переведен и сохранен как titanic.csv!") 
dannye = pd.read_csv("titanic.csv") # снова открываем наш новый файл titanic.csv для проверки

klassy = ["1 класс", "2 класс", "3 класс"] # создаем список подписей для трех классов билетов на графике
vyzhivshie = [0, 0, 0] # создаем список для подсчета выживших в каждом классе (сначала везде нули)

for i in range(len(dannye)): # запускаем цикл по всем строкам таблицы от первой до последней
    klass_bileta = dannye["Pclass"][i] # берем класс билета текущего пассажира
    vyzhil = dannye["Survived"][i] # берем статус выживания (1 — выжил, 0 — погиб)
    
    if vyzhil == 1: # если пассажир выжил
        if klass_bileta == 1: # если у него был 1-й класс
            vyzhivshie[0] = vyzhivshie[0] + 1 # прибавляем 1 в первую ячейку списка выживших
        elif klass_bileta == 2: # если у него был 2-й класс
            vyzhivshie[1] = vyzhivshie[1] + 1 # прибавляем 1 во вторую ячейку списка выживших
        elif klass_bileta == 3: # если у него был 3-й класс
            vyzhivshie[2] = vyzhivshie[2] + 1 # прибавляем 1 в третью ячейку списка выживших
print(vyzhivshie) # выводим в терминал готовый список с количеством выживших по классам
plt.bar(klassy, vyzhivshie, color="skyblue", edgecolor="black") # строим столбчатую диаграмму: снизу классы, высота столбиков — число выживших
plt.title("Выживаемость пассажиров в зависимости от класса билета") # добавляем заголовок над графиком
plt.xlabel("Класс билета") # подписываем нижнюю ось
plt.ylabel("Количество выживших пассажиров") # подписываем левую ось
plt.show() # показываем график на экране
