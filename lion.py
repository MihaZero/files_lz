import docx # подключаем библиотеку для работы с файлами Word
import matplotlib.pyplot as plt # подключаем библиотеку для рисования графиков
print("1. Открываю файл lion.docx...") 
doc = docx.Document("lion.docx") # открываем файл lion.docx
text = "" # создаем пустую текстовую переменную, куда будем собирать весь текст из документа
for p in doc.paragraphs: # проходим по каждому абзацу документа
    text = text + p.text + " " # склеиваем абзацы через пробел
text = text.lower() # переводим все заглавные буквы в тексте в маленькие
print("2. Текст прочитан! Всего символов:", len(text)) # выводим общее число символов для контроля
print("3. Начинаю подсчет букв и слов...") # сообщаем о начале главного цикла

letters = [] # сюда складываем уникальные буквы
letter_counts = [] # сюда складываем сколько раз каждая буква встретилась
words = [] # сюда складываем уникальные слова
word_counts = [] # сюда складываем сколько раз каждое слово встретилось
total_words = 0 # общее количество слов
slovo = "" # переменная для сборки текущего слова
alfavit = "абвгдеёжзийклмнопрстуфхцчшщъыьэюяabcdefghijklmnopqrstuvwxyz" # строка со всеми русскими и английскими буквами для проверки

for simvol in text: # идем по каждой букве в тексте
    if simvol in alfavit: # проверяем, есть ли символ в нашем алфавите
        slovo = slovo + simvol # приклеиваем букву к текущему слову
        nashel_bukvu = False # ставим флажок в положение «не нашел», так как мы еще не искали эту букву в списке
        for i in range(len(letters)): # запускаем цикл по номерам ячеек списка letters
            if letters[i] == simvol: # проверяем, лежит ли в ячейке под номером i наша текущая буква
                letter_counts[i] = letter_counts[i] + 1 # если буква нашлась, прибавляем 1 в ячейку с таким же номером i в списке количеств
                nashel_bukvu = True # поднимаем флажок «нашел»
        if nashel_bukvu == False: # если букву не нашли, добавляем ее в конец списка
            letters.append(simvol) # добавляем эту новую букву в конец списка всех уникальных букв
            letter_counts.append(1) # добавляем единицу в конец списка количеств
    else: # срабатывает, если символ НЕ буква (наткнулись на пробел, точку, запятую или цифру)
        if slovo != "": # проверяем, успели ли накопиться буквы в переменной slovo
            total_words = total_words + 1 # увеличиваем общий счетчик всех слов в тексте на 1
            
            if total_words % 5000 == 0: # проверяем, делится ли число слов на 5000 без остатка
                print("Обработано слов:", total_words) # выводим прогресс каждые 5000 слов, чтобы видеть работу программы
                
            nashel_slovo = False # ставим флажок в положение «не нашел»
            for i in range(len(words)): # запускаем цикл по номерам ячеек списка уже найденных слов
                if words[i] == slovo: # проверяем, совпадает ли слово в ячейке под номером i с нашим собранным словом
                    word_counts[i] = word_counts[i] + 1 # если слово нашлось, прибавляем 1 в ячейку с таким же номером i в списке количеств
                    nashel_slovo = True # поднимаем флажок «нашел»
            if nashel_slovo == False: # если после проверки всего списка флажок так и остался «не нашел»
                words.append(slovo) # добавляем новое слово в конец списка всех уникальных слов
                word_counts.append(1) # добавляем единицу в конец списка количеств
            slovo = "" # полностью очищаем переменную slovo для следующего слова

# Если текст закончился без точки или пробела в самом конце, дозаписываем последнее слово
if slovo != "": # проверяем, не осталось ли последнее слово необработанным
    total_words = total_words + 1 # увеличиваем общий счетчик слов
    nashel_slovo = False # ставим флажок «не нашел»
    for i in range(len(words)): # ищем последнее слово в списке
        if words[i] == slovo: # если нашли
            word_counts[i] = word_counts[i] + 1 # прибавляем 1
            nashel_slovo = True # ставим флажок «нашел»
    if nashel_slovo == False: # если не нашли
        words.append(slovo) # добавляем в список
        word_counts.append(1) # ставим количество 1

print("4. Подсчет завершен! Всего слов в тексте:", total_words) 
iskomoe_slovo = input("Введите слово для поиска: ") 
iskomoe_slovo = iskomoe_slovo.lower() # переводим введенное слово в маленькие буквы, чтобы поиск сработал точно

skolko_raz = 0 # сюда запишем, сколько раз повторилось слово (пока ставим 0)
for i in range(len(words)): # проходим по всем уникальным словам из нашего списка
    if words[i] == iskomoe_slovo: # если нашли слово, которое ввел пользователь
        skolko_raz = word_counts[i] # забираем его количество повторений из списка количеств

if total_words > 0: # проверяем, что в тексте вообще были слова (чтобы не поделить на ноль)
    procent = (skolko_raz / total_words) * 100 # считаем процент: делим количество найденного слова на все слова и умножаем на 100
else: 
    procent = 0 

procent = int(procent * 100) / 100 # округляем до 2 знаков после запятой вашим способом

file = open("tablica.csv", "w", encoding="utf-8-sig") # создаем и открываем файл tablica.csv для записи
file.write("Слово;Сколько раз повторилось;Частота встречи в %\n") # записываем первую строчку — шапку таблицы
stroka = iskomoe_slovo + ";" + str(skolko_raz) + ";" + str(procent) + "%\n" # склеиваем строчку с результатом через плюсики
file.write(stroka) # записываем строчку в файл
file.close() # закрываем файл, чтобы данные сохранились
print("таблица для вашего слова сохранена в файл tablica.csv!") 
plt.bar(letters, letter_counts) # строим столбчатую диаграмму (гистограмму) по спискам букв и их количеств
plt.title("Буквы в тексте") # добавляем заголовок сверху над графиком
plt.xlabel("Буквы") # подписываем нижнюю горизонтальную ось
plt.ylabel("Сколько раз") # подписываем левую вертикальную ось
plt.show() # открываем готовое окно с графиком на экране

